import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { GitSync } from '../electron/git-sync';
import { DataStore } from '../electron/storage';
import { PreferencesStore } from '../electron/preferences';
import { FolderStorage } from '../electron/folder-storage';
import { DocumentFiles } from '../electron/document-files';
import { temporaryDirectory } from './helpers';
const exec = promisify(execFile);
const git = (cwd: string, args: string[]) => exec('git', args, { cwd, windowsHide: true, encoding: 'utf8', env: { ...process.env, GIT_TERMINAL_PROMPT: '0' } });
test('real Git initializes only the data repository, stages, commits literal messages, pushes and pulls a local remote', async t => {
  const root = await temporaryDirectory(t); const global = path.join(root, 'global'); await writeFile(global, '');
  const prior = process.env.GIT_CONFIG_GLOBAL; process.env.GIT_CONFIG_GLOBAL = global;
  t.after(() => { if (prior === undefined) delete process.env.GIT_CONFIG_GLOBAL; else process.env.GIT_CONFIG_GLOBAL = prior; });
  const store = new DataStore(path.join(root, 'profile')); await store.initialize();
  const prefs = new PreferencesStore(store.directory); await prefs.initialize();
  const folders = new FolderStorage(store, prefs, undefined, new DocumentFiles(store.directory, { settleMs: 0 })); await folders.initialize();
  const sync = new GitSync(folders, prefs); assert.equal((await sync.status()).repository, false);
  await assert.rejects(sync.action({ type: 'add' }), /启用/);
  const remote = path.join(root, 'remote.git'); await mkdir(remote); await git(remote, ['init', '--bare', '--initial-branch=main']);
  const status = await sync.configure({ enabled: true, initialize: true, remote, userName: 'GTodo QA', userEmail: 'qa@example.test' });
  assert.equal(status.repository, true); assert.equal(status.enabled, true);
  await folders.update(engine => { engine.apply({ type: 'notebook.add', title: 'Git 笔记' }); engine.apply({ type: 'note.update', id: engine.state.notes[0].id, patch: { content: '# 本机版本' } }); });
  await writeFile(path.join(folders.directory, 'recovery.bak'), 'kept locally');
  await sync.action({ type: 'add' }); assert.equal((await sync.status()).files.some(file => file.path.endsWith('.bak')), false);
  const message = '中文提交 $() `literal` "quote"'; await sync.action({ type: 'commit', message });
  assert.equal((await git(folders.directory, ['log', '-1', '--format=%s'])).stdout.trim(), message);
  await sync.action({ type: 'push' });
  const clone = path.join(root, 'remote-edit'); await git(root, ['clone', '--branch', 'main', remote, clone]);
  await git(clone, ['config', 'user.name', 'Other QA']); await git(clone, ['config', 'user.email', 'other@example.test']);
  const relative = path.join('documents', 'notes', `note-${store.engine.state.notes[0].id}`, 'note.md');
  await writeFile(path.join(clone, relative), '# 远端修改'); await git(clone, ['add', '--all']); await git(clone, ['commit', '-m', 'remote edit']); await git(clone, ['push']);
  await sync.action({ type: 'pull' }); await folders.refresh();
  assert.equal(store.engine.state.notes[0].values.content, '# 远端修改'); assert.equal(await readFile(path.join(folders.directory, relative), 'utf8'), '# 远端修改');
  await assert.rejects(sync.action({ type: 'pull' }), /未提交/);
  await sync.configure({ enabled: false }); assert.equal((await sync.status()).enabled, false);
  const moved = path.join(root, 'moved'); await mkdir(moved); await folders.changeDirectory(moved); assert.equal(prefs.value.git.enabled, false);
});
test('Git rejects a parent repository instead of staging unrelated files and preserves data on errors', async t => {
  const root = await temporaryDirectory(t); await git(root, ['init', '--initial-branch=main']);
  const store = new DataStore(path.join(root, 'profile')); await store.initialize(); const prefs = new PreferencesStore(store.directory); await prefs.initialize();
  const folders = new FolderStorage(store, prefs); await folders.initialize(); const sync = new GitSync(folders, prefs);
  const status = await sync.status(); assert.equal(status.repository, false); assert.match(status.error!, /另一个 Git 仓库/);
  await assert.rejects(sync.configure({ enabled: true }), /另一个 Git 仓库/);
  assert.equal(prefs.value.git.enabled, false); assert.equal((await git(root, ['diff', '--cached', '--name-only'])).stdout, '');
  const unavailable = new GitSync(folders, prefs, 'nonexistent-gtodo-git'); assert.match((await unavailable.status()).error!, /未找到 Git/);
});
